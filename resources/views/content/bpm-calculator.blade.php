<h2>
Wat is BPM en waarom krijgt u geld terug bij export?
</h2>
<p>
BPM (Belasting van personenauto's en motorrijwielen) is
een Nederlandse belasting die wordt betaald wanneer een
auto voor het eerst in Nederland op kenteken komt.
Afhankelijk van de brandstofsoort en de CO₂-uitstoot
gaat het om enkele honderden tot tienduizenden euro's.
</p>
<p>
Verlaat de auto Nederland definitief en wordt hij in een
ander EU-land ingeschreven, dan krijgt u
<strong>het deel van de BPM terug dat nog in de waarde van
de auto zit</strong>: de rest-BPM. U vraagt die aan bij de Belastingdienst,
nadat de auto bij de RDW is afgemeld voor export. Bij
een jonge auto kan dat om een flink bedrag gaan, dus het
loont om dit goed te regelen.
</p>

<h2>Hoe werkt de BPM-berekening in deze calculator?</h2>
<p>
U voert uw kenteken in en wij halen bij de RDW twee
gegevens op: de datum waarop de auto voor het eerst op
kenteken kwam en
<strong>de oorspronkelijke BPM zoals de RDW die heeft
geregistreerd</strong>
(de bruto BPM). Op dat bedrag passen wij de vaste
afschrijvingstabel van de Belastingdienst toe: hoe meer
maanden de auto oud is, hoe groter het deel dat al is
afgeschreven. Wat overblijft, is de BPM die u
terugkrijgt.
</p>
<p>
Staat de oorspronkelijke BPM niet bij de RDW, dan
benaderen wij die met de officiële BPM-tarieven op basis
van CO₂-uitstoot en brandstofsoort. De uitkomst is
altijd een indicatie. Is uw auto meer in waarde gedaald
dan de tabel aanneemt, bijvoorbeeld door een hoge
kilometerstand of schade, dan kan een taxatierapport van
een erkend taxateur een hogere teruggave opleveren.
<a href="/contact">Vraag het ons gerust</a> als u
twijfelt wat in uw geval voordeliger is.
</p>

