<h2>
BPM-teruggave en de kosten van auto invoeren in Spanje
</h2>
<p>
De BPM-teruggave staat los van de Spaanse
registratiebelasting, de IEDMT (<em>Impuesto Especial sobre Determinados Medios de
Transporte</em>). De BPM krijgt u terug in Nederland; de IEDMT betaalt
u in Spanje, afhankelijk van de CO₂-uitstoot.
<strong>Verhuist u uw hoofdverblijf naar Spanje, dan kunt u
onder voorwaarden vrijstelling van de IEDMT
aanvragen.</strong>
De auto moet dan onder meer al minimaal zes maanden op
uw naam staan.
</p>
<p>
Op de <a href="/tarieven">tarievenpagina</a> ziet u alle
kosten op een rij: onze vaste pakketprijs en de Spaanse
kosten, zoals de ITV-keuring (de Spaanse APK), de leges,
de kentekenplaten en de gestoría (het Spaanse
administratiekantoor dat de inschrijving indient).
</p>

<h2>Zelf regelen of uitbesteden?</h2>
<p>
U kunt de teruggave zelf aanvragen. U heeft dan het
juiste formulier van de Belastingdienst nodig, de
exportdocumenten van de RDW en het Spaanse
kentekenbewijs, en dat alles binnen de termijn van 13
weken. In de praktijk gaat het vaak mis op de timing: de
Spaanse inschrijving duurt langer dan verwacht, of er
ontbreekt een document.
</p>
